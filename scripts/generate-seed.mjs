import { writeFileSync } from "node:fs";
import { SAMPLE_WEDDINGS } from "../lib/weddings/sample-data.ts";
import { TEMPLATES } from "../lib/weddings/templates.ts";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const jq = (v) => `$json$${JSON.stringify(v)}$json$::jsonb`;
const lines = [];

lines.push("-- Seed: template registry + 5 demo weddings (idempotent).");
lines.push("-- Generated by scripts/generate-seed.mjs from lib/weddings/{templates,sample-data}.ts");
lines.push("");

for (const t of TEMPLATES) {
  lines.push(`insert into public.templates (slug, name, category, description, thumbnail, fonts, palette, sections, animation, active, sort_order)
values (${q(t.slug)}, ${q(t.name)}, ${q(t.category)}, ${q(t.description)}, ${q(t.thumbnail)}, ${jq(t.fonts)}, ${jq(t.palette)}, ${jq(t.sections)}, ${q(t.animation)}, ${t.active}, ${t.sortOrder})
on conflict (slug) do update set
  name = excluded.name, category = excluded.category, description = excluded.description,
  thumbnail = excluded.thumbnail, fonts = excluded.fonts, palette = excluded.palette,
  sections = excluded.sections, animation = excluded.animation, active = excluded.active,
  sort_order = excluded.sort_order;`);
}
lines.push("");

for (const w of SAMPLE_WEDDINGS) {
  const weddingDate = new Date(w.couple.countdownDate).toISOString().slice(0, 10);
  lines.push(`insert into public.wedding_websites (slug, template_id, status, bride_name, groom_name, wedding_date, expiry_days, rsvp_enabled, locale_default)
values (${q(w.slug)}, (select id from public.templates where slug = ${q(w.templateSlug)}), ${q(w.status)}, ${q(w.couple.bride)}, ${q(w.couple.groom)}, ${q(weddingDate)}::date, 7, false, ${q(w.localeDefault)})
on conflict (slug) do nothing;`);

  const wid = `(select id from public.wedding_websites where slug = ${q(w.slug)})`;
  const { photo, ...couple } = w.couple;
  const events = w.events.map(({ image, ...e }) => e);
  const content = {
    couple,
    events,
    venue: w.venue,
    contacts: w.contacts,
    sections: { ...w.sections, rsvp: false },
    hashtag: w.hashtag,
    music: w.music,
    blessing: w.blessing,
    blessingHi: w.blessingHi,
    mantra: w.mantra,
    videoUrl: w.videoUrl,
  };
  for (const [key, value] of Object.entries(content)) {
    if (value === undefined) continue;
    lines.push(`insert into public.wedding_content (website_id, key, value)
values (${wid}, ${q(key)}, ${jq(value)})
on conflict (website_id, key) do update set value = excluded.value, updated_at = now();`);
  }

  const images = [];
  if (photo) images.push({ slot: "couple", path: photo, alt: `${w.couple.bride} and ${w.couple.groom}`, caption: null, sort: 0 });
  w.gallery.forEach((g, i) => images.push({ slot: "gallery", path: g.src, alt: g.alt, caption: g.caption ?? null, sort: i }));
  for (const e of w.events) {
    if (e.image) images.push({ slot: `event:${e.id}`, path: e.image, alt: e.name, caption: null, sort: 0 });
  }
  for (const img of images) {
    lines.push(`insert into public.wedding_images (website_id, slot, storage_path, alt, caption, sort_order)
values (${wid}, ${q(img.slot)}, ${q(img.path)}, ${q(img.alt)}, ${img.caption === null ? "null" : q(img.caption)}, ${img.sort})
on conflict (website_id, slot, sort_order) do update set storage_path = excluded.storage_path, alt = excluded.alt, caption = excluded.caption;`);
  }
  lines.push("");
}

writeFileSync(new URL("../supabase/migrations/0002_seed_demo_data.sql", import.meta.url), lines.join("\n"));
console.log("seed written:", lines.length, "lines");
